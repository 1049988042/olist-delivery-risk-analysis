"""Replay existing analyses in an isolated venv and compare stored statistics.

No new analysis/model is introduced. The five historical source files are copied
unchanged; existing outputs are read only. Run prepare_workspace.py first.
"""
from pathlib import Path
import datetime, hashlib, json, math, os, subprocess, sys, time

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'final_delivery'
WORK=ROOT/'.repro_runs'/'clean_env'
PY=WORK/'.venv'/('Scripts/python.exe' if os.name=='nt' else 'bin/python')
LOG=WORK/'logs'
LOG.mkdir(exist_ok=True)
records=[]

def command(args,name,stdout_path=None):
    started=time.perf_counter()
    env=os.environ.copy();env.pop('PYTHONPATH',None)
    env.update(PYTHONUTF8='1',PYTHONHASHSEED='0',MPLCONFIGDIR=str(WORK/'matplotlib_cache'),PIP_DISABLE_PIP_VERSION_CHECK='1')
    result=subprocess.run([str(PY),'-X','utf8',*args],cwd=WORK,env=env,capture_output=True,text=True,encoding='utf-8',errors='replace')
    (LOG/(name+'.stdout.txt')).write_text(result.stdout,encoding='utf-8')
    (LOG/(name+'.stderr.txt')).write_text(result.stderr,encoding='utf-8')
    if stdout_path and result.returncode==0:stdout_path.write_text(result.stdout,encoding='utf-8')
    records.append({'name':name,'command':['<isolated-venv-python>','-X','utf8',*args],'cwd':'.repro_runs/clean_env','exit_code':result.returncode,'elapsed_seconds':round(time.perf_counter()-started,3),'stdout_log':str((LOG/(name+'.stdout.txt')).relative_to(ROOT)).replace('\\','/'),'stderr_log':str((LOG/(name+'.stderr.txt')).relative_to(ROOT)).replace('\\','/'),'stderr_nonempty':bool(result.stderr.strip())})
    print(f'{name}: exit={result.returncode}, elapsed={records[-1]["elapsed_seconds"]}s',flush=True)
    write_summary('running')
    if result.returncode:raise RuntimeError(f'{name} failed: see local logs')
    return result.stdout

def write_summary(status,**more):
    summary={'status':status,'executed_on_client_date':'2026-10-17','isolated_venv':True,'system_site_packages':False,'vendored_audit_deps_copied':False,'commands':records,'comparison_rtol':1e-4,'comparison_atol':1e-6,'non_scientific_fields_not_compared':['iterations','iteration_count','score_gradient_max_abs','condition_number'],'scope_limitations':['Windows/Python 3.12 only; Linux/macOS not executed','Historical hand-written baseline/deep reports are preserved, not generated by the analysis scripts','Binary-identical PNG files and font availability on other operating systems are not guaranteed','No source-system validation, experiment, or deployed monitoring system']}
    summary.update(more)
    (OUT/'reproducibility.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2),encoding='utf-8')

def compare_json(a,b,path='',skip=()):
    if isinstance(a,dict):
        assert a.keys()==b.keys(),path
        for k in a:
            if k not in skip:compare_json(a[k],b[k],path+'/'+k,skip)
    elif isinstance(a,list):
        assert len(a)==len(b),path
        for i,(x,y) in enumerate(zip(a,b)):compare_json(x,y,path+'/'+str(i),skip)
    elif isinstance(a,bool) or a is None or isinstance(a,str):assert a==b,(path,a,b)
    elif isinstance(a,int):assert a==b,(path,a,b)
    else:assert math.isclose(a,b,rel_tol=1e-4,abs_tol=1e-6),(path,a,b)

def main():
    assert PY.exists(),'Run prepare_workspace.py first'
    write_summary('running')
    install=['-m','pip','install','-r',str(ROOT/'requirements-repro.txt')]
    if (OUT/'environment.freeze.txt').exists():install+=['-c',str(OUT/'environment.freeze.txt')]
    command(install,'pinned_install')
    command(['-m','pip','check'],'pip_check')
    freeze=command(['-m','pip','freeze'],'pip_freeze')
    (OUT/'environment.freeze.txt').write_text(freeze,encoding='utf-8')
    command(['-c',"import sys,json,statsmodels;print(json.dumps({'python':sys.version,'statsmodels_file':statsmodels.__file__,'system_site_packages_used':sys.prefix==sys.base_prefix}))"],'environment_probe')
    command(['audit_olist.py'],'audit',WORK/'audit_results.json')
    command(['run_project.py'],'baseline')
    command(['deep_audit.py'],'deep')
    command(['review_timing_study.py'],'review_timing')
    json_files=['audit_results.json','project/metrics.json','deep_study/deep_metrics.json','review_timing_study/timing_metrics.json']
    skipped=('iterations','iteration_count','score_gradient_max_abs','condition_number')
    for name in json_files:
        replay=json.loads((WORK/name).read_text(encoding='utf-8-sig'))
        if name=='audit_results.json' and not (ROOT/name).exists():
            reference=json.loads((OUT/'audit_reference.json').read_text(encoding='utf-8'))
            replay['reviews'].pop('examples',None)
        else:reference=json.loads((ROOT/name).read_text(encoding='utf-8-sig'))
        compare_json(reference,replay,skip=skipped)
    # Uses venv pandas; all aggregate CSVs must agree, not just headline metrics.
    comparison_code="""
from pathlib import Path
import pandas as pd,json
root=Path(__ROOT__);work=Path.cwd();checked=[]
for directory in ['project','deep_study','review_timing_study']:
 for original in sorted((root/directory).glob('*.csv')):
  rel=original.relative_to(root);rerun=work/rel
  assert rerun.exists(),str(rel)
  pd.testing.assert_frame_equal(pd.read_csv(original),pd.read_csv(rerun),check_dtype=False,check_exact=False,rtol=1e-4,atol=1e-6)
  checked.append(str(rel).replace('\\\\','/'))
print(json.dumps(checked))
""".replace('__ROOT__',repr(str(ROOT)))
    csvs=json.loads(command(['-c',comparison_code],'csv_comparison'))
    figures=[str(p.relative_to(WORK)).replace('\\','/') for d in ['project','deep_study','review_timing_study'] for p in (WORK/d).rglob('*.png')]
    assert len(figures)==5,figures
    for figure in figures:assert (WORK/figure).stat().st_size>1000
    manifest_path=WORK/'input_manifest.json'
    source_manifest=json.loads((manifest_path if manifest_path.exists() else OUT/'historical_manifest.json').read_text(encoding='utf-8'))
    unchanged=[]
    for rel,expected in source_manifest.items():
        actual=hashlib.sha256((ROOT/rel).read_bytes()).hexdigest()
        assert actual==expected,rel
        unchanged.append(rel)
    write_summary('passed',compared_json=json_files,compared_csv=csvs,regenerated_figures=figures,historical_files_unchanged=len(unchanged),historical_output_directories_untouched=True)
    print(f'PASS: {len(json_files)} JSON and {len(csvs)} CSV outputs match; {len(figures)} figures regenerated.',flush=True)

if __name__=='__main__':
    try:main()
    except Exception as e:
        write_summary('failed',failure_type=type(e).__name__,failure_message=str(e))
        raise
